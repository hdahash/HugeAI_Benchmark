"""A small mock LLM router used to demo/self-test routerbench without needing
a real backend or API keys. Not part of the framework itself -- swap it for
the user's real router by pointing configs/*.yaml at its base_url.

Routing logic (deliberately simple/legible so the sample dataset's
expected_model labels line up with it):
  - prompt asking for step-by-step derivation/proof, or long-context (>250
    chars) -> "large-model"
  - prompt referencing code/regex/sql/refactor, or medium length -> "medium-model"
  - everything else -> "small-model"

Supports fault injection via the `X-Inject-Fault` header (returns 500s and
artificial slowness at a configurable rate) so the reliability scenario has
something real to exercise.
"""
from __future__ import annotations

import asyncio
import random
import time

from fastapi import FastAPI, Header, Request
from fastapi.responses import JSONResponse

app = FastAPI(title="Mock LLM Router")

REASONING_KEYWORDS = ("step by step", "prove", "derive", "algorithm complexity")
CODE_KEYWORDS = ("code", "function", "regex", "sql", "refactor", "bug", "fibonacci")

MODEL_PROFILES = {
    "small-model": {"base_latency_s": 0.05, "jitter_s": 0.03},
    "medium-model": {"base_latency_s": 0.15, "jitter_s": 0.08},
    "large-model": {"base_latency_s": 0.45, "jitter_s": 0.2},
}

FAULT_RATE = 0.35  # fraction of fault-injected requests that actually fail


def choose_model(prompt: str) -> str:
    text = prompt.lower()
    if len(prompt) > 250 or any(k in text for k in REASONING_KEYWORDS):
        return "large-model"
    if any(k in text for k in CODE_KEYWORDS) or len(prompt) > 60:
        return "medium-model"
    return "small-model"


def fake_answer(prompt: str, model: str) -> str:
    text = prompt.lower()
    if "capital of france" in text:
        return "The capital of France is Paris."
    if "mix blue and yellow" in text:
        return "Mixing blue and yellow paint produces green."
    if "leap year" in text:
        return "A leap year has 366 days."
    if "chemical symbol for gold" in text:
        return "The chemical symbol for gold is Au."
    if "romeo and juliet" in text:
        return "Romeo and Juliet was written by William Shakespeare."
    if "boiling point of water" in text:
        return "Water boils at 100 degrees Celsius at sea level."
    if "red planet" in text:
        return "Mars is known as the Red Planet."
    if "freezing point of water" in text and "fahrenheit" in text:
        return "Water freezes at 32 degrees Fahrenheit."
    if "17 sheep" in text:
        return "9 sheep are left -- 'all but 9 die' means 9 survive, not that 9 die."
    if "def" in text or "function" in text or "palindrome" in text or "fibonacci" in text:
        return f"def solution():\n    # generated by {model}\n    pass\n"
    return f"[{model}] Response to: {prompt[:80]}"


@app.post("/v1/chat/completions")
async def chat_completions(request: Request, x_inject_fault: str | None = Header(default=None)):
    body = await request.json()
    messages = body.get("messages", [])
    prompt = messages[-1]["content"] if messages else ""
    forced_model = body.get("model")

    if x_inject_fault and random.random() < FAULT_RATE:
        failure_kind = random.choice(["error", "slow"])
        if failure_kind == "error":
            return JSONResponse(status_code=500, content={"error": "simulated upstream failure"})
        await asyncio.sleep(6.0)  # exceeds typical client timeout -> surfaces as a timeout

    model = forced_model if forced_model in MODEL_PROFILES else choose_model(prompt)
    profile = MODEL_PROFILES[model]

    length_penalty = min(len(prompt) / 2000, 1.0) * 0.3
    await asyncio.sleep(profile["base_latency_s"] + random.random() * profile["jitter_s"] + length_penalty)

    content = fake_answer(prompt, model)
    input_tokens = max(len(prompt.split()), 1)
    output_tokens = max(len(content.split()), 1)

    return {
        "id": f"cmpl-{int(time.time() * 1000)}",
        "model": model,
        "choices": [{"message": {"role": "assistant", "content": content}}],
        "usage": {"prompt_tokens": input_tokens, "completion_tokens": output_tokens},
    }


@app.get("/health")
async def health():
    return {"status": "ok"}
